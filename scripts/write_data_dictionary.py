"""Regenerate docs/DATA_DICTIONARY.md from the column list in src/ml2/schema.py.

    python scripts/write_data_dictionary.py
"""

from __future__ import annotations

import json
from pathlib import Path

from ml2.config import load_config, resolve
from ml2.schema import NOT_FEATURES, column_dictionary

ROOT = Path(__file__).resolve().parents[1]

INTRO = """# Data dictionary: `bond_month_panel`

One row per corporate bond per month-end. Same columns in the group database table `ml2.bond_month_panel`
and in `data/processed/bond_month_panel.parquet`.
Generated by `scripts/write_data_dictionary.py` from `src/ml2/schema.py`; edit there, not here.

## Sources

| Source | What it gives |
|---|---|
| TRACE Enhanced (FINRA's corporate bond trade reports, via WRDS), cleaned | Each bond's yield, price and volume on each trading day |
| TRACE corporate bond master file | Issuer, stock ticker, coupon, maturity, 144A flag, grade, debt type |
| US Treasury par yield curve (treasury.gov) | The benchmark the spread is measured against |
| FRED (ICE BofA spread indices, VIX) and the New York Fed (SOFR) | Market backdrop |
| Daily stock prices, shares outstanding, quarterly balance sheets, GICS sectors | The issuer's equity features, always as known on the snapshot date |

## Rows kept

Straight corporate bonds with a fixed coupon, not convertible, issued by a company with a listed stock,
traded on the month-end day, 1 to 30.5 years to maturity, yield between 0% and 40%, spread between -100 and 3,000 bp.

The issuer's stock data (equity columns and sector) is left empty where the company behind the bond's ticker
cannot be confirmed as the bond's issuer, by its issuer code (first 6 CUSIP characters) or by its name.
The bond rows stay; the manifest counts them.

The grade (IG or HY) is the TRACE flag from the bond's latest master record. Where that record is newer than all
the bond's trades (usually written as the bond nears maturity and its ratings are withdrawn), the bond takes the
majority grade of its company's other bonds instead. The manifest counts these bonds too.

## Columns

Some columns contain the target or future information and must never be model inputs (list at the end).
`ml2.schema.feature_columns()` returns the allowed inputs.
"""

GROUP_TITLES = {
    "id": "Identifiers",
    "target": "Target (regression, main report)",
    "annex": "Annex target (classification, Naive Bayes)",
    "bond": "Bond terms",
    "liquidity": "Liquidity",
    "issuer": "Issuer structure and sector",
    "equity": "Issuer's stock and balance sheet (as of the snapshot date)",
    "macro": "Rates and market backdrop (same for every bond on a date)",
}


def main() -> None:
    cd = column_dictionary()
    lines = [INTRO]
    for group, title in GROUP_TITLES.items():
        lines.append(f"\n### {title}\n\n| Column | Description |\n|---|---|")
        for _, row in cd[cd["group"] == group].iterrows():
            lines.append(f"| `{row['column']}` | {row['description']} |")
    lines.append(f"\n**Not allowed as model inputs:** {', '.join(f'`{c}`' for c in NOT_FEATURES)}.")

    manifest_path = resolve(load_config()["paths"]["manifest"])
    if manifest_path.exists():
        m = json.loads(manifest_path.read_text(encoding="utf-8"))
        lines.append("\n## Last build\n")
        lines.append(f"- Built (UTC): {m['built_at_utc']}")
        lines.append(f"- Rows: {m['rows']:,}; bonds: {m['bonds']:,}; issuers: {m['issuers']:,}; "
                     f"snapshots: {m['snapshots']} ({m['first_snapshot']} to {m['last_snapshot']})")
        lines.append(f"- Rows by partition: {m['rows_by_partition']}")
        lines.append(f"- Rows by grade: {m['rows_by_grade']}")
        lines.append(f"- Parquet sha256: `{m['sha256']}`")

    out = ROOT / "docs" / "DATA_DICTIONARY.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
